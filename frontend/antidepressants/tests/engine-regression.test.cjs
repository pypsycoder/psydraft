const fs=require('fs'),vm=require('vm'),path=require('path');
const html=fs.readFileSync(path.join(__dirname,'..','src','compass.html'),'utf8');
const js=html.split('<script>')[1].split('</script>')[0];
const controls={};
for(const m of html.matchAll(/<select id="([^"]+)"[^>]*>([\s\S]*?)<\/select>/g))controls[m[1]]={tagName:'SELECT',options:Array.from(m[2].matchAll(/<option value="([^"]*)"/g),o=>({value:o[1]}))};
controls.age={tagName:'INPUT'};
const ctx={document:{getElementById:id=>controls[id]}};vm.createContext(ctx);
const prefix=js.slice(0,js.indexOf('for(const [group,items]'));
const core=js.slice(js.indexOf('const has='),js.indexOf('function itemList('));
const options=js.slice(js.indexOf('const COURSE_OPTIONS='),js.indexOf('const COURSE_LABELS='));
const empty=js.slice(js.indexOf('function emptyCourse()'),js.indexOf('function courseControl('));
const validator=js.slice(js.indexOf('function validateImport('),js.indexOf("$('file').onchange"));
vm.runInContext(prefix+core+options+empty+validator+';globalThis.api={calculate,validateImport,DRUGS,SOURCES};',ctx);
controls.previous.options.push(...ctx.api.DRUGS.map(d=>({value:d.id})));
vm.runInContext(fs.readFileSync(path.join(__dirname,'safety-scenarios.js'),'utf8'),ctx);
const results=ctx.runSafetyScenarios(ctx.api),failed=results.filter(x=>!x.passed);
console.log(JSON.stringify({assertions:results.length,failures:failed},null,2));
if(failed.length)process.exitCode=1;
vm.runInContext(fs.readFileSync(path.join(__dirname,'..','src','bridge-map.js'),'utf8'),ctx);
vm.runInContext(fs.readFileSync(path.join(__dirname,'bridge-scenarios.js'),'utf8'),ctx);
const bridge=ctx.runBridgeScenarios(ctx.mapPsyDraftSnapshot,ctx.api),bad=bridge.filter(x=>!x.passed);console.log(JSON.stringify({bridgeAssertions:bridge.length,failed:bad},null,2));if(bad.length)process.exitCode=1;
